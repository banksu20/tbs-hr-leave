-- Explicit database-created tests only. No public fixture-creation endpoint.
CREATE TABLE IF NOT EXISTS tbs_intern_decision_tests (
 id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 2000000000) PRIMARY KEY,
 test_key text NOT NULL UNIQUE, recipient text NOT NULL,
 token uuid NOT NULL DEFAULT gen_random_uuid(), revision text NOT NULL DEFAULT md5(gen_random_uuid()::text),
 snapshot jsonb NOT NULL, expires_at timestamptz NOT NULL DEFAULT now()+interval '24 hours',
 decision text CHECK(decision IN ('approve','reject')), decided_at timestamptz, rejection_reason text,
 job_id uuid REFERENCES tbs_sync_jobs(id)
);
CREATE OR REPLACE FUNCTION tbs_isolated_intern_decision(payload jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE t tbs_intern_decision_tests%ROWTYPE; BEGIN
 SELECT * INTO t FROM tbs_intern_decision_tests WHERE id=(payload->>'id')::integer FOR UPDATE;
 IF t.id IS NULL OR t.token::text IS DISTINCT FROM payload->>'token' OR t.revision IS DISTINCT FROM payload->>'revision' OR t.expires_at<=now() THEN RETURN jsonb_build_object('ok',false,'statusCode',409,'error','This test link is invalid or expired.'); END IF;
 IF t.recipient IS DISTINCT FROM payload->>'accountId' THEN RETURN jsonb_build_object('ok',false,'statusCode',403,'error','This test belongs to a different LINE account.'); END IF;
 IF t.decision IS NOT NULL THEN RETURN jsonb_build_object('ok',false,'statusCode',409,'error','This test has already been decided. No real leave was changed.'); END IF;
 IF payload->>'action'='review' THEN RETURN jsonb_build_object('ok',true,'isolatedTest',true,'request',jsonb_build_object('name',t.snapshot->>'user_name','type',t.snapshot->>'leave_type','dates',t.snapshot->>'selected_dates','days',(t.snapshot->>'leave_days')::numeric,'period',t.snapshot->>'half_day_period','reason',t.snapshot->>'reason')); END IF;
 IF COALESCE(payload->>'action','') NOT IN ('approve','reject') THEN RETURN jsonb_build_object('ok',false,'statusCode',422,'error','Invalid test action'); END IF;
 UPDATE tbs_intern_decision_tests SET decision=payload->>'action',decided_at=now(),rejection_reason=left(COALESCE(payload->>'reason',''),1000) WHERE id=t.id;
 RETURN jsonb_build_object('ok',true,'isolatedTest',true);
END $$;
DO $$ DECLARE def text; BEGIN
 SELECT pg_get_functiondef('tbs_intern_decision(jsonb)'::regprocedure) INTO def;
 IF strpos(def,'tbs_isolated_intern_decision(payload)')=0 THEN
  IF strpos(def,'BEGIN')=0 THEN RAISE EXCEPTION 'Decision entry point missing'; END IF;
  def:=regexp_replace(def,'BEGIN', $patch$BEGIN
 IF EXISTS(SELECT 1 FROM tbs_intern_decision_tests WHERE id=(payload->>'id')::integer) THEN RETURN tbs_isolated_intern_decision(payload); END IF;
$patch$);
  EXECUTE def;
 END IF;
END $$;
CREATE OR REPLACE FUNCTION tbs_isolated_intern_card(test_id integer) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE t tbs_intern_decision_tests%ROWTYPE; r leave_requests%ROWTYPE; message jsonb; link text; BEGIN
 SELECT * INTO STRICT t FROM tbs_intern_decision_tests WHERE id=test_id;
 IF EXISTS(SELECT 1 FROM leave_requests WHERE id=t.id) THEN RAISE EXCEPTION 'Test ID conflicts with a real request'; END IF;
 r:=jsonb_populate_record(NULL::leave_requests,t.snapshot||jsonb_build_object('id',t.id,'decision_token',t.token));
 message:=tbs_approval_message_before_intern(r,jsonb_build_array(t.recipient));
 link:='https://liff.line.me/2008617589-89gR1Y3Y/leave-decision?id='||t.id||'&token='||t.token||'&revision='||t.revision;
 RETURN jsonb_set(message,'{messages,0,contents,footer,contents}',jsonb_build_array(
  jsonb_build_object('type','button','style','primary','action',jsonb_build_object('type','uri','label','Approve','uri',link||'&action=approve')),
  jsonb_build_object('type','button','style','secondary','action',jsonb_build_object('type','uri','label','Reject','uri',link||'&action=reject'))));
END $$;
COMMIT;
